import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, test } from "node:test";
import { createEmbeddingCache } from "../../server/services/embeddingCache.js";

const temporaryDirectories = [];

async function createCachePath() {
  const directory = await mkdtemp(join(tmpdir(), "shopease-embedding-cache-test-"));
  temporaryDirectories.push(directory);
  return join(directory, "embeddings.json");
}

afterEach(async () => {
  await Promise.all(temporaryDirectories.splice(0).map((directory) =>
    rm(directory, { recursive: true, force: true }),
  ));
});

test("persists embeddings and reuses them across cache instances", async () => {
  const cachePath = await createCachePath();
  let generationCount = 0;
  const firstCache = createEmbeddingCache({
    cachePath,
    model: "test-embedding-model",
    embedText: async () => {
      generationCount += 1;
      return [0.25, 0.75];
    },
  });
  const chunk = { chunkId: "chunk-1", text: "Approved chunk text" };

  assert.deepEqual(await firstCache.getEmbedding(chunk), [0.25, 0.75]);
  const cacheFile = JSON.parse(await readFile(cachePath, "utf8"));
  assert.equal(cacheFile.model, "test-embedding-model");
  assert.equal(cacheFile.entries.length, 1);
  assert.match(cacheFile.entries[0].textHash, /^[a-f0-9]{64}$/);

  const secondCache = createEmbeddingCache({
    cachePath,
    model: "test-embedding-model",
    embedText: async () => {
      throw new Error("Cached embedding should be reused.");
    },
  });
  assert.deepEqual(await secondCache.getEmbedding(chunk), [0.25, 0.75]);
  assert.equal(generationCount, 1);
});

test("regenerates and replaces an embedding when chunk text changes", async () => {
  const cachePath = await createCachePath();
  let generationCount = 0;
  const cache = createEmbeddingCache({
    cachePath,
    model: "test-embedding-model",
    embedText: async (text) => {
      generationCount += 1;
      return text === "Original text" ? [1, 0] : [0, 1];
    },
  });

  assert.deepEqual(
    await cache.getEmbedding({ chunkId: "chunk-1", text: "Original text" }),
    [1, 0],
  );
  assert.deepEqual(
    await cache.getEmbedding({ chunkId: "chunk-1", text: "Updated text" }),
    [0, 1],
  );
  const cacheFile = JSON.parse(await readFile(cachePath, "utf8"));
  assert.equal(generationCount, 2);
  assert.equal(cacheFile.entries.length, 1);
  assert.deepEqual(cacheFile.entries[0].embedding, [0, 1]);
});

test("does not reuse embeddings generated by a different model", async () => {
  const cachePath = await createCachePath();
  const originalCache = createEmbeddingCache({
    cachePath,
    model: "model-a",
    embedText: async () => [1, 0],
  });
  await originalCache.getEmbedding({ chunkId: "chunk-1", text: "Text" });

  let generationCount = 0;
  const updatedCache = createEmbeddingCache({
    cachePath,
    model: "model-b",
    embedText: async () => {
      generationCount += 1;
      return [0, 1];
    },
  });
  assert.deepEqual(
    await updatedCache.getEmbedding({ chunkId: "chunk-1", text: "Text" }),
    [0, 1],
  );
  const cacheFile = JSON.parse(await readFile(cachePath, "utf8"));
  assert.equal(generationCount, 1);
  assert.equal(cacheFile.model, "model-b");
  assert.equal(cacheFile.entries.length, 1);
});

test("deduplicates concurrent embedding requests for the same chunk", async () => {
  const cachePath = await createCachePath();
  let generationCount = 0;
  const cache = createEmbeddingCache({
    cachePath,
    model: "test-embedding-model",
    embedText: async () => {
      generationCount += 1;
      await new Promise((resolve) => setTimeout(resolve, 10));
      return [0.5, 0.5];
    },
  });
  const chunk = { chunkId: "chunk-1", text: "Shared chunk text" };

  const results = await Promise.all([
    cache.getEmbedding(chunk),
    cache.getEmbedding(chunk),
    cache.getEmbedding(chunk),
  ]);
  assert.deepEqual(results, [[0.5, 0.5], [0.5, 0.5], [0.5, 0.5]]);
  assert.equal(generationCount, 1);
});

test("rejects malformed cache contents rather than silently discarding them", async () => {
  const cachePath = await createCachePath();
  const { writeFile } = await import("node:fs/promises");
  await writeFile(cachePath, "{invalid", "utf8");
  const cache = createEmbeddingCache({
    cachePath,
    model: "test-embedding-model",
    embedText: async () => [1, 0],
  });

  await assert.rejects(
    cache.getEmbedding({ chunkId: "chunk-1", text: "Text" }),
    /Embedding cache contains invalid JSON/,
  );
});

test("rejects generated vectors with invalid values or inconsistent dimensions", async (t) => {
  await t.test("invalid vector values", async () => {
    const cache = createEmbeddingCache({
      cachePath: await createCachePath(),
      model: "test-embedding-model",
      embedText: async () => [Number.NaN],
    });
    await assert.rejects(
      cache.getEmbedding({ chunkId: "chunk-1", text: "Text" }),
      /finite numbers/,
    );
  });

  await t.test("inconsistent dimensions", async () => {
    let generationCount = 0;
    const cache = createEmbeddingCache({
      cachePath: await createCachePath(),
      model: "test-embedding-model",
      embedText: async () => {
        generationCount += 1;
        return generationCount === 1 ? [1, 0] : [1, 0, 0];
      },
    });
    await cache.getEmbedding({ chunkId: "chunk-1", text: "First text" });
    await assert.rejects(
      cache.getEmbedding({ chunkId: "chunk-2", text: "Second text" }),
      /3 dimensions; expected 2/,
    );
  });
});
